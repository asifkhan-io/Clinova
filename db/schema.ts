/* ---------------------------------- rate limits ---------------------------------- */
// Fixed-window counters (ARCH2). Deliberately NOT tenant-owned, so no
// clinic_id: a limit protects the platform from one caller, and a caller is
// not clinic data. `identifier_hash` is always a sha256 — never a raw IP or
// phone number, so a database dump leaks neither (scope §8).

export const rateLimits = pgTable(
  "rate_limits",
  {
    bucket: text("bucket").notNull(),
    identifierHash: text("identifier_hash").notNull(),
    windowStart: timestamp("window_start", { withTimezone: true }).notNull(),
    count: integer("count").notNull().default(0),
  },
  (t) => [
    primaryKey({ columns: [t.bucket, t.identifierHash, t.windowStart] }),
    // Lets the sweep drop expired windows without scanning the table.
    index("rate_limits_window_idx").on(t.windowStart),
    check("rate_limits_count_positive", sql`${t.count} > 0`),
  ],
);

/* ------------------------------- notification runs ------------------------------- */
// At-most-once guard for scheduled emails (Phase 8d). The morning digest claims
// (clinic, 'morning_digest', local date) BEFORE sending: a retried or duplicated
// cron run finds the row and sends nothing. The trade is deliberate — missing
// one digest is better than a clinic getting the same email twice and learning
// to ignore it.

export const notificationRuns = pgTable(
  "notification_runs",
  {
    clinicId: uuid("clinic_id")
      .notNull()
      .references(() => clinics.id, { onDelete: "cascade" }),
    kind: text("kind").notNull(),
    runKey: text("run_key").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.clinicId, t.kind, t.runKey] })],
);
